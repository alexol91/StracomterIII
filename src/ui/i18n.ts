const dicts: Record<Lang, Record<string, string>> = { es, en };

let lang: Lang = 'es';
const listeners = new Set<() => void>();

export function getLang(): Lang { return lang; }

/** Cambia de idioma en caliente y avisa a quien dibuja. */
export function setLang(l: Lang): void {
  if (l !== 'es' && l !== 'en') l = 'es';
  if (l === lang) return;
  lang = l;
  try { document.documentElement.lang = l; } catch { /* sin DOM */ }
  for (const f of Array.from(listeners)) f();
}

/** Suscripción al cambio de idioma. Devuelve la función para darse de baja. */
export function onLangChange(fn: () => void): () => void {
  listeners.add(fn);
  return () => { listeners.delete(fn); };
}

/** Traduce una clave, sustituyendo {param}. Si falta la clave en el idioma activo, cae al español y por último a la propia clave. */
export function t(key: Key | string, params?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? dicts.es[key] ?? key;
  if (params) {
    for (const k of Object.keys(params)) s = s.split(`{${k}}`).join(String(params[k]));
  }
  return s;
}
